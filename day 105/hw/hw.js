// 2) Props-ით მიღებული მონაცემების პირდაპირ შეცვლა არ შეიძლება.
// Props კომპონენტისთვის მხოლოდ წასაკითხია. მონაცემის შეცვლა უნდა მოხდეს
// მშობელ კომპონენტში, მაგალითად state-ის გამოყენებით, შემდეგ კი ახალი
