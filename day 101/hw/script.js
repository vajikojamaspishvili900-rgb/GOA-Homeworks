// 1. რას ნიშნავს conditional rendering React-ში?
// 2. როგორ შეგვიძლია React-ში ელემენტის ჩვენება მხოლოდ მაშინ, როცა პირობა true არის?
// 3. რას აკეთებს ეს კოდი თუ isLoggedIn დააბრუნებს Trueს?
// {isLoggedIn && <h1>Welcome!</h1>}

// 4. როგორ ვიყენებთ ternary operator-ს React-ში?

// 5. რა განსხვავებაა &&-ით და ternary operator-ით პირობის დაწერას შორის React-ში?



// 1) Conditional rendering React-ში ნიშნავს, რომ ჩვენ შეგვიძლია ვაჩვენოთ ან დავმალოთ კომპონენტები ან ელემენტები DOM-ში, დამოკიდებულია გარკვეულ პირობებზე. ეს საშუალებას გვაძლევს შექმნათ დინამიური UI, რომელიც რეაგირებს აპლიკაციის მდგომარეობაზე.

// 2) React-ში ელემენტის ჩვენება მხოლოდ მაშინ, როცა პირობა true არის, შეგვიძლია გამოიყენოთ JavaScript-ის ლოგიკური ოპერატორი &&. მაგალითად:
// {isLoggedIn && <h1>Welcome!</h1>}
// ეს ნიშნავს, რომ თუ isLoggedIn არის true, მაშინ <h1>Welcome!</h1> იქნება გამოჩენილი. თუ isLoggedIn არის false, არაფერი არ გამოჩნდება.

// 3) თუ isLoggedIn დააბრუნებს true-ს, მაშინ კოდი {isLoggedIn && <h1>Welcome!</h1>} გამოაჩენს <h1>Welcome!</h1> ელემენტს. თუ isLoggedIn არის false, არაფერი არ გამოჩნდება.

// 4) Ternary operator-ს React-ში ვიყენებთ იმისთვის, რომ შევამოწმოთ პირობა და დავბრუნოთ ორი შესაძლო შედეგიდან ერთი. სინტაქსი არის შემდეგი:

// condition ? expressionIfTrue : expressionIfFalse

// მაგალითად:
// {isLoggedIn ? <h1>Welcome!</h1> : <h1>Please log in.</h1>}
// ეს ნიშნავს, რომ თუ isLoggedIn არის true, გამოჩნდება <h1>Welcome!</h1>, ხოლო თუ false, გამოჩნდება <h1>Please log in.</h1>.


// 5) && ოპერატორი გამოიყენება მხოლოდ იმისთვის, რომ ვაჩვენოთ ელემენტი, თუ პირობა true არის, ხოლო ternary operator საშუალებას გვაძლევს დავბრუნოთ ორი განსხვავებული შედეგი, დამოკიდებულია პირობაზე. && ოპერატორი არ გვაძლევს შესაძლებლობას დავბრუნოთ ალტერნატიული ელემენტი, თუ პირობა false არის, მაშინ როცა ternary operator გვაძლევს ორივე შესაძლო შედეგის განსაზღვრას.
