function Student(props) {
    return (
        <div>
            <p>სახელი: {props.name}</p>
            <p>ასაკი: {props.age}</p>
            <p>შეფასება: {props.grade}</p>
        </div>
    );
}

// 4) Button კომპონენტი Props-ით იღებს text-ს։
function Button(props) {
    return <button>{props.text}</button>;
}

// App კომპონენტში ვაჩვენებთ სამ ღილაკს ტექსტით։
function App() {
    return (
        <div>
            <Student name="ანა" age={20} grade="A" />

            <Button text="დაწყება" />
            <Button text="გაგრძელება" />
            <Button text="დასრულება" />

            <Card>
                <p>ეს ტექსტი Card კომპონენტის შიგნით გამოჩნდება.</p>
            </Card>
        </div>
    );
}

// 5) Card კომპონენტი props.children-ის გამოყენებით აჩვენებს
// მის შიგნით გადაცემულ შიგთავსს։
function Card(props) {
    return <div className="card">{props.children}</div>;
}



